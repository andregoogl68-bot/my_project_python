import random  # Импортируем модуль для генерации случайных чисел и выбора случайных элементов

# Функция для сохранения контактов в файл
def save_contacts(contacts, filename):
    with open(filename, "wt", encoding="utf-8") as out_file:      # Открываем файл для записи в кодировке UTF-8
        out_file.write("[\n")                                     # Открываем список в формате Python-литерала
        for c in contacts:                                        # Перебираем все сгенерированные контакты
            out_file.write(f"    {c!r},\n")                       # Записываем словарь контакта как литерал Python
        out_file.write("]\n")                                     # Закрываем список

# Список имён для генерации
names = ["Андрей", "Иван", "Мария", "Ольга", "Дмитрий", "Елена", "Сергей", "Анна", "Павел", "Татьяна",
         "Алексей", "Екатерина", "Николай", "Светлана", "Михаил", "Ирина", "Владимир", "Наталья", "Артём", "Юлия"]  # Список доступных имён

# Список фамилий для генерации
surnames = ["Иванов", "Петров", "Смирнов", "Кузнецов", "Соколов", "Попов", "Лебедев", "Козлов", "Новиков", "Морозов",
            "Волков", "Соловьёв", "Васильев", "Зайцев", "Павлов", "Семёнов", "Голубев", "Виноградов", "Богданов", "Воробьёв"]  # Список доступных фамилий

# Список комментариев для генерации
comments = ["рабочий", "личный", "домашний", "мобильный", "друг", "коллега", "родственник", "сосед",
            "знакомый", "клиент", "партнёр", "руководитель", "секретарь", "курьер", "врач", ""]  # Список возможных комментариев

contacts = []                                                     # Создаём пустой список для хранения сгенерированных контактов

for i in range(1, 201):                                           # Цикл от 1 до 200 включительно для генерации 200 записей
    first = random.choice(names)                                  # Случайное имя
    last = random.choice(surnames)                                # Случайная фамилия
    number = f"+7 {random.randint(100, 999)}-{random.randint(100, 999)}-{random.randint(10, 99)}-{random.randint(10, 99)}"  # Генерируем номер телефона в формате +7 XXX-XXX-XX-XX
    comment = random.choice(comments)                             # Случайный комментарий
    contacts.append({                                             # Добавляем сгенерированный контакт в список
        "Id": i,                                                  # Порядковый номер как ID
        "имя": first,                                             # Имя
        "фамилия": last,                                          # Фамилия
        "Номер": number,                                          # Телефон
        "комментарий": comment,                                   # Комментарий
    })                                                            # Закрываем словарь

filename = input("Имя файла для сохранения: ")                    # Запрашиваем у пользователя имя файла для сохранения
save_contacts(contacts, filename)                                 # Сохраняем сгенерированные данные в указанный файл

print(f"Файл {filename} создан с 100 записями.")                  # Выводим сообщение об успешном создании файла