import re                                                     # Импортируем модуль для работы с регулярными выражениями

# Функция для вывода всех номеров из словаря numbers
def print_numbers(numbers):
    print("Телефонный номер:")                                # Выводим заголовок
    for k, v in numbers.items():                              # Перебираем все пары ключ-значение в словаре
        print("имя:", k, "\tНомер:", v)                       # Выводим имя и номер, разделяя табуляцией
        print()                                               # Выводим пустую строку для разделения записей


# Функция для добавления новой записи в словарь
def add_number(numbers, name, number):
    numbers[name] = number                                    # Присваиваем словарю по ключу name значение number


# Функция для поиска номера по имени
def lookup_numbers(numbers, name):
    if name in numbers:                                       # Если имя есть в словаре
        return "Номер - " + numbers[name]                     # Возвращаем строку с номером
    return name + " не найдено"                               # Иначе возвращаем сообщение, что не найдено


# Функция для удаления записи по имени
def remove_number(numbers, name):
    if name in numbers:                                         # Если имя есть в словаре
        del numbers[name]                                       # Удаляем запись по ключу
    else:
        print(name, "не найдено")                               # Иначе выводим сообщение, что не найдено


# Функция для загрузки номеров из файла
def load_numbers(numbers, filename):
    pattern = re.compile(
        r'"имя"\s*:\s*"([^"]*)"\s*,\s*"номер"\s*:\s*"([^"]*)"'   # Регулярное выражение под формат: "имя": "Имя", "номер": "Номер"
        ) 

    loaded = 0                                                   # Счётчик загруженных записей
    skipped = 0                                                  # Счётчик пропущенных строк   

    with open(filename, "rt", encoding="utf-8-sig") as in_file:  # utf-8-sig автоматически убирает BOM, если он есть
        for line_num, line in enumerate(in_file, start=1):       # Перебираем строки файла с нумерацией, начиная с 1
            line = line.strip()                                  # Убираем пробельные символы в начале и конце строки
            if not line:                                         # Пропускаем пустые строки
                continue
            match = pattern.search(line)                         # Ищем совпадение с шаблоном в строке
            if match:                                            # Если совпадение найдено
                name, number = match.group(1), match.group(2)    # Извлекаем имя и номер из групп
                numbers[name] = number                           # Добавляем запись в словарь
                loaded += 1                                      # Увеличиваем счётчик загруженных записей
            else:
                print(f"Строка {line_num} пропущена (неверный формат): {line}")  # Не падаем, а сообщаем о некорректной строке
                skipped += 1                                    # Увеличиваем счётчик загруженных строк
    print(f"Загружено записей: {loaded}, пропущено: {skipped}") # Выводим итоги загрузки


# Функция для сохранения номеров в файл
def save_numbers(numbers, filename):
    with open(filename, "wt", encoding="utf-8") as out_file:    # Открываем файл для записи в кодировке UTF-8
        for k, v in numbers.items():                            # Перебираем все пары ключ-значение
            out_file.write(f'"имя": "{k}", "номер": "{v}"\n')   # Записываем строку в формате '"имя": "Имя", "номер": "Номер"'


# Функция для вывода меню
def print_menu():
    print('1. Вывод телефонных номеров')                        # Выводим пункты меню
    print('2. Добавить номер телефона')
    print('3. Удалить номер телефона')
    print('4. Поиск телефонного номера')
    print('5. Загрузить номера телефонов')
    print('6. Сохранить номера телефонов')
    print('7. Выход')
    print()                                                     # Пустая строка для отделения меню


pfone_list = {}                                                 # Создаём пустой словарь для хранения телефонных номеров

while True:                                                     # Цикл while для работы с меню
    print_menu()                                                # Показываем меню

    try:                                                        # Пытаемся выполнить ввод и преобразование
        menu_choice = int(input("Введите число (1-7): "))       # Запрашиваем у пользователя выбор пункта меню и преобразуем в целое число
    except ValueError:                                          # Если введено не число
        print("Нужно ввести число от 1 до 7")                   # Сообщаем об ошибке
        print()                                                 # Пустая строка для отделения
        continue                                                # Возвращаемся к началу цикла

    if menu_choice == 1:                                        # Если выбран пункт 1 — выводим все номера
        print_numbers(pfone_list)                               # Вызываем функцию вывода всех номеров из словаря
    elif menu_choice == 2:                                      # Если выбран пункт 2 — добавляем новый номер
        name = input("Имя: ")                                   # Запрашиваем имя
        phone = input("номер: ")                                # Запрашиваем номер
        add_number(pfone_list, name, phone)                     # Добавляем в словарь
    elif menu_choice == 3:                                      # Если выбран пункт 3 — удаляем запись
        name = input("Имя: ")                                   # Запрашиваем имя
        remove_number(pfone_list, name)                         # Удаляем из словаря
    elif menu_choice == 4:                                      # Если выбран пункт 4 — ищем номер
        name = input("Имя: ")                                   # Запрашиваем имя
        print(lookup_numbers(pfone_list, name))                 # Выводим результат поиска6
    elif menu_choice == 5:                                      # Если выбран пункт 5 — загружаем из файла
        filename = input("Имя файла для загрузки: ")            # Запрашиваем имя файла
        try:                                                    # Пытаемся выполнить загрузку из файла
            load_numbers(pfone_list, filename)                  # Загружаем данные
        except FileNotFoundError:                               # Если файл не найден
            print(f"Файл не найден: {filename}")                # Выводит "Файл не найден"
    elif menu_choice == 6:                                      # Если выбран пункт 6 — сохраняем в файл
        filename = input("Имя файла для сохранения: ")          # Запрашиваем имя файла
        save_numbers(pfone_list, filename)                      # Сохраняем данные
    elif menu_choice == 7:                                      # Если выбран пункт 7 — выходим из цикла
        break                                                   # Прерывание
    else:                                                       # Если введено число вне диапазона 1-7
        print("Нет такого пункта меню. Введите число от 1 до 7.") # Выводим нет такого пункта меню
        print()                                                 # Пустая строка для отделения

print("До свидания")                                            # После выхода из цикла выводим "До свидания"